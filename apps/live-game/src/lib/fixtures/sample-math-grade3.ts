function cell(
  category: string,
  points: 100 | 200 | 300 | 400 | 500,
  question: string,
  choices: [string, string, string, string],
  correct_index: 0 | 1 | 2 | 3,
  teks: string,
  daily_double = false,
): QuestionCell {
  return {
    id: `${category.slice(0, 3).toLowerCase()}-${points}`,
    category,
    points,
    question,
    choices,
    correct_index,
    answer: choices[correct_index],
    teks,
    daily_double,
  };
}

