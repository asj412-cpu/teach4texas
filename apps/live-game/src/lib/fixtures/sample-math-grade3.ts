export function buildSampleMathGrade3Board(
  id = "board_sample_math_g3",
): GameBoard {
  const now = new Date().toISOString();
  const cells: QuestionCell[] = [];
  for (const cat of categories) {
    for (const row of bank[cat]) {
      cells.push(
        cell(
          cat,
          row.points,
          row.question,
          row.choices,
          row.correct_index,
          row.teks,
          row.daily_double,
        ),
      );
    }
  }
  return {
    id,
    title: "STAAR Math Game Show — Grade 3 Sample",
    grade: 3,
    subject: "math",
    theme: "Game Show",
    status: "ready",
    tpt_sku: "t4t-math-g3-gameshow-sample",
    cells,
    created_at: now,
    updated_at: now,
  };
}
